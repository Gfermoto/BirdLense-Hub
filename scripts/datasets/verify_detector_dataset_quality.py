#!/usr/bin/env python3
"""Verify detector dataset quality gates from exported profile JSON (#394)."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


CLASSES = ('birds', 'rodent', 'background')
SPLITS = ('train', 'val')


def _parse_thresholds(raw: str, *, default: dict[str, int]) -> dict[str, int]:
    """Parse ``class=value`` pairs into threshold mapping."""
    out = dict(default)
    text = (raw or '').strip()
    if not text:
        return out
    for chunk in text.split(','):
        item = chunk.strip()
        if not item:
            continue
        if '=' not in item:
            raise ValueError(f'invalid threshold item: {item!r}')
        key, val = (x.strip().lower() for x in item.split('=', 1))
        if key not in out:
            raise ValueError(f'unknown class in threshold: {key!r}')
        out[key] = int(val)
    return out


def _load_profile(path: Path) -> dict[str, Any]:
    """Load profile JSON generated by export_detector_dataset_profile.py."""
    data = json.loads(path.read_text(encoding='utf-8'))
    if not isinstance(data, dict):
        raise ValueError('profile root must be object')
    return data


def verify_quality(
    profile: dict[str, Any],
    *,
    min_train: dict[str, int],
    min_val: dict[str, int],
    max_train_imbalance_ratio: float,
    min_source_tags: dict[str, int],
    max_unknown_tag_share: float,
    min_background_share_train: float,
    max_background_share_train: float,
) -> tuple[bool, dict[str, Any]]:
    """Run quality gates and return ``(ok, summary)``."""
    errors: list[str] = []
    classes = profile.get('classes')
    if not isinstance(classes, dict):
        return False, {'ok': False, 'errors': ['profile.classes missing']}

    train_counts: dict[str, int] = {}
    for cls in CLASSES:
        cls_row = classes.get(cls)
        if not isinstance(cls_row, dict):
            errors.append(f'missing_class:{cls}')
            continue
        for split in SPLITS:
            split_row = cls_row.get(split)
            if not isinstance(split_row, dict):
                errors.append(f'missing_split:{cls}:{split}')
                continue
            images = int(split_row.get('images') or 0)
            labels = int(split_row.get('labels') or 0)
            tags = split_row.get('source_tags') or {}
            if not isinstance(tags, dict):
                tags = {}

            if split == 'train':
                train_counts[cls] = images
                if images < min_train[cls]:
                    errors.append(
                        f'train_images_below_min:{cls}:{images}<{min_train[cls]}',
                    )
            if split == 'val' and images < min_val[cls]:
                errors.append(
                    f'val_images_below_min:{cls}:{images}<{min_val[cls]}',
                )
            if labels != images:
                errors.append(
                    f'label_image_parity_failed:{cls}:{split}:{labels}!={images}',
                )

            nonzero_tags = sum(1 for _k, v in tags.items() if int(v or 0) > 0)
            if nonzero_tags < min_source_tags[cls]:
                errors.append(
                    f'source_diversity_low:{cls}:{split}:{nonzero_tags}'
                    f'<{min_source_tags[cls]}',
                )
            unknown = int(tags.get('unknown') or 0)
            unknown_share = (unknown / images) if images else 0.0
            if unknown_share > max_unknown_tag_share:
                errors.append(
                    f'unknown_source_share_high:{cls}:{split}:'
                    f'{unknown_share:.4f}>{max_unknown_tag_share:.4f}',
                )

    if len(train_counts) == len(CLASSES):
        max_train = max(train_counts.values())
        min_train_count = min(train_counts.values()) if train_counts else 0
        if min_train_count <= 0:
            errors.append('train_counts_invalid_zero')
        else:
            ratio = max_train / float(min_train_count)
            if ratio > max_train_imbalance_ratio:
                errors.append(
                    'train_imbalance_ratio_high:'
                    f'{ratio:.4f}>{max_train_imbalance_ratio:.4f}',
                )
        total_train = sum(train_counts.values())
        if total_train > 0:
            bg_share = train_counts['background'] / float(total_train)
            if bg_share < min_background_share_train:
                errors.append(
                    f'background_share_too_low:{bg_share:.4f}<'
                    f'{min_background_share_train:.4f}',
                )
            if bg_share > max_background_share_train:
                errors.append(
                    f'background_share_too_high:{bg_share:.4f}>'
                    f'{max_background_share_train:.4f}',
                )

    summary = {
        'ok': len(errors) == 0,
        'errors': errors,
        'thresholds': {
            'min_train': min_train,
            'min_val': min_val,
            'max_train_imbalance_ratio': max_train_imbalance_ratio,
            'min_source_tags': min_source_tags,
            'max_unknown_tag_share': max_unknown_tag_share,
            'min_background_share_train': min_background_share_train,
            'max_background_share_train': max_background_share_train,
        },
        'profile_dataset_root': profile.get('dataset_root'),
    }
    return summary['ok'], summary


def parse_args() -> argparse.Namespace:
    """Parse CLI arguments."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', required=True, help='profile JSON path')
    parser.add_argument(
        '--min-train',
        default='birds=300,rodent=120,background=120',
        help=(
            'Min train images per class, e.g. '
            'birds=300,rodent=120,background=120'
        ),
    )
    parser.add_argument(
        '--min-val',
        default='birds=60,rodent=24,background=24',
        help=(
            'Min val images per class, e.g. '
            'birds=60,rodent=24,background=24'
        ),
    )
    parser.add_argument('--max-train-imbalance-ratio', type=float, default=8.0)
    parser.add_argument(
        '--min-source-tags',
        default='birds=2,rodent=2,background=1',
        help='Minimum non-empty source tags per class per split',
    )
    parser.add_argument('--max-unknown-tag-share', type=float, default=0.35)
    parser.add_argument(
        '--min-background-share-train',
        type=float,
        default=0.10,
    )
    parser.add_argument(
        '--max-background-share-train',
        type=float,
        default=0.60,
    )
    return parser.parse_args()


def main() -> int:
    """CLI entrypoint."""
    args = parse_args()
    profile = _load_profile(Path(args.profile).resolve())
    min_train = _parse_thresholds(
        args.min_train,
        default={'birds': 300, 'rodent': 120, 'background': 120},
    )
    min_val = _parse_thresholds(
        args.min_val,
        default={'birds': 60, 'rodent': 24, 'background': 24},
    )
    min_source_tags = _parse_thresholds(
        args.min_source_tags,
        default={'birds': 2, 'rodent': 2, 'background': 1},
    )
    ok, summary = verify_quality(
        profile,
        min_train=min_train,
        min_val=min_val,
        max_train_imbalance_ratio=float(args.max_train_imbalance_ratio),
        min_source_tags=min_source_tags,
        max_unknown_tag_share=float(args.max_unknown_tag_share),
        min_background_share_train=float(args.min_background_share_train),
        max_background_share_train=float(args.max_background_share_train),
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0 if ok else 1


if __name__ == '__main__':
    raise SystemExit(main())
